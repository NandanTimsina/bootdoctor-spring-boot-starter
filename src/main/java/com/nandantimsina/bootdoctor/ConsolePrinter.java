package com.nandantimsina.bootdoctor;

import java.util.Locale;

public final class ConsolePrinter {

    static final int WIDTH = 70;

    private ConsolePrinter() {
    }

    public static void print(String title, String body) {
        String line = "=".repeat(70);
        StringBuilder sb = new StringBuilder();
        sb.append(System.lineSeparator());
        sb.append(line).append(System.lineSeparator());
        sb.append(" ").append(title).append(System.lineSeparator());
        sb.append(line).append(System.lineSeparator());
        sb.append(body).append(System.lineSeparator());
        sb.append(line).append(System.lineSeparator());
        System.err.print(sb);
    }

    public static String formatDiagnosis(ResponseParser.Diagnosis d, String model, long millis) {
        String nl = System.lineSeparator();
        StringBuilder sb = new StringBuilder();
        if (d.structured()) {
            sb.append(wrap("Likely cause : ", d.cause(), WIDTH)).append(nl);
            sb.append(wrap("Suggested fix: ", d.fix(), WIDTH)).append(nl);
            sb.append("Confidence   : ").append(d.confidence()).append(nl);
            if (!d.evidence().isEmpty()) {
                sb.append("Evidence:").append(nl);
                for (String e : d.evidence()) {
                    sb.append(wrap("  - ", e, WIDTH)).append(nl);
                }
            }
        } else {
            sb.append("The model did not return the expected format. Raw answer:").append(nl);
            sb.append(wrap("", d.cause(), WIDTH)).append(nl);
        }
        sb.append(nl).append(String.format(Locale.ROOT,
                "AI-generated by %s in %.1f s. It can be wrong, check before acting.",
                model, millis / 1000.0));
        return sb.toString();
    }

    static String wrap(String label, String text, int width) {
        String indent = " ".repeat(label.length());
        StringBuilder out = new StringBuilder();
        StringBuilder line = new StringBuilder(label);
        for (String word : text.split("\\s+")) {
            if (word.isEmpty()) {
                continue;
            }
            if (line.length() > indent.length() && line.length() + 1 + word.length() > width) {
                out.append(line).append(System.lineSeparator());
                line = new StringBuilder(indent);
            }
            if (line.length() > indent.length()) {
                line.append(' ');
            }
            line.append(word);
        }
        out.append(line);
        return out.toString();
    }
}